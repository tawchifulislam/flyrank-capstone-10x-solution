import PDFDocument from "pdfkit";

export function buildPdf(record, out) {
  const { topic, map } = record;
  const doc = new PDFDocument({ size: "A4", margin: 56 });
  doc.pipe(out);

  function heading(text) {
    doc.moveDown(1);
    doc.font("Helvetica-Bold").fontSize(15).fillColor("#111111").text(text);
    doc.moveDown(0.4);
  }

  function body(text) {
    doc.font("Helvetica").fontSize(11).fillColor("#222222").text(text);
  }

  const steps = [...map.steps].sort((a, b) => a.order - b.order);
  const totalMinutes = steps.reduce((sum, step) => sum + step.minutes, 0);

  doc.font("Helvetica-Bold").fontSize(26).fillColor("#111111").text(topic);
  doc.moveDown(0.3);
  doc
    .font("Helvetica")
    .fontSize(11)
    .fillColor("#666666")
    .text(`Beginner learning map. Estimated total time: ${totalMinutes} minutes.`);

  heading("Before you start");
  doc.font("Helvetica").fontSize(11).fillColor("#222222");
  doc.list(map.prerequisites, { bulletRadius: 2, textIndent: 12 });

  heading("Steps in order");
  steps.forEach((step, index) => {
    if (index > 0) doc.moveDown(0.6);
    doc
      .font("Helvetica-Bold")
      .fontSize(12)
      .fillColor("#111111")
      .text(`${step.order}. ${step.title} (${step.minutes} min)`);
    body(step.why);
  });

  heading("Your first project");
  body(map.first_project);

  heading("Common mistakes");
  doc.font("Helvetica").fontSize(11).fillColor("#222222");
  doc.list(map.common_mistakes, { bulletRadius: 2, textIndent: 12 });

  doc.moveDown(2);
  doc
    .font("Helvetica-Oblique")
    .fontSize(9)
    .fillColor("#888888")
    .text("Generated by TopicMap with AI. Use it as a starting map and verify details in official docs.");

  doc.end();
}
